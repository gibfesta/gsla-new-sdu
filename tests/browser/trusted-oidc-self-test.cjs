'use strict';
const assert=require('node:assert/strict');
const {classifyPreflight,classify}=require('./trusted-oidc-classifier.cjs');
const {tests}=require('./catalogue.json');
const ids=['GSLA-M1-021-AUTO-009','GSLA-M1-021-AUTO-010','GSLA-M1-021-AUTO-011','GSLA-M1-021-AUTO-012'];
for(const id of ids)assert.equal(tests.filter(t=>t.id===id).length,1);
const f=id=>tests.find(t=>t.id===id);
const pre={status:401,path:'/api/facilities',json:true,appError:true,redirected:false,vercelMitigated:false};
assert.equal(classifyPreflight(pre).status,'PASS');
assert.equal(classifyPreflight({...pre,status:200}).status,'BLOCKED');
assert.equal(classifyPreflight({...pre,appError:false}).status,'BLOCKED');
assert.equal(classifyPreflight({...pre,vercelMitigated:true}).status,'BLOCKED');
assert.equal(classify(f(ids[0]),{finalPath:'/sign-in',redirected:true,redirectPath:'/sign-in'},true).status,'PASS');
assert.equal(classify(f(ids[0]),{finalPath:'/organisation/home',redirected:false},true).status,'FAIL');
assert.equal(classify(f(ids[2]),{status:401,json:true,appError:true},true).status,'PASS');
assert.equal(classify(f(ids[3]),{status:401,json:true,appError:true,cachePrivateNoStore:false,varyCookie:false},true).status,'FAIL');
assert.equal(classify(f(ids[3]),{status:401,json:true,appError:true,cachePrivateNoStore:true,varyCookie:true},true).status,'PASS');
assert.equal(classify(f(ids[2]),{status:200,json:false,appError:false},false).status,'BLOCKED');
const secret='SYNTHETIC_OIDC_SECRET_DO_NOT_LOG_897412';
assert.ok(!JSON.stringify(classifyPreflight({...pre,secret})).includes(secret));
assert.ok(!JSON.stringify(classify(f(ids[2]),{status:401,json:true,appError:true,secret},true)).includes(secret));
console.log('PASS: immutable IDs 009-012, app boundary, PASS/FAIL/BLOCKED, cache/Vary, synthetic secret non-disclosure');
